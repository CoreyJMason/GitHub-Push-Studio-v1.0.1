const { test } = require('node:test')
const assert = require('node:assert/strict')
const os = require('node:os')
const path = require('node:path')
const fs = require('node:fs/promises')
const { execFileSync } = require('node:child_process')
const { initialize, getRepo, commit, push } = require('../electron/git-service.cjs')

test('initialize -> check changes -> commit -> clean working tree', async () => {
  const project = await fs.mkdtemp(path.join(os.tmpdir(), 'push-studio-test-'))
  try {
    await fs.writeFile(path.join(project, 'app.js'), 'console.log("test")\n')
    let repo = await initialize(project)
    assert.equal(repo.initialized, true)
    assert.equal(repo.branch, 'main')
    assert.equal(repo.ignored, true)
    execFileSync('git', ['config', '--local', 'user.name', 'Test Developer'], { cwd: project })
    execFileSync('git', ['config', '--local', 'user.email', 'test@example.com'], { cwd: project })
    await fs.writeFile(path.join(project, '.env'), 'TEST_SECRET=redacted\n')
    repo = await getRepo(project)
    assert.ok(repo.total >= 2)
    assert.ok(!repo.files.some(x => x.path === '.env'), 'default ignore protects environment files')
    const result = await commit(project, 'Initial commit')
    assert.equal(result.committed, true)
    assert.equal((await getRepo(project)).total, 0)
    assert.equal((await getRepo(project)).hasCommits, true)
    await assert.rejects(push(project), /Connect or create a GitHub repository/)
  } finally { await fs.rm(project, { recursive: true, force: true }) }
})
